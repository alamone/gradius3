"""キューブラッシュの並び（純正の法則）: 高さ(H) × シフト(S) × タイプ(T) → 最初のキューブが出る瞬間のフレームカウンタ
純正では各キューブの高さの番号 = (カウンタ下位 xor 上位) の bit2-5。出る間隔は固定(16フレームの倍数)なので、
最初の1個の瞬間のカウンタ c0 で99個すべての並びが決まる（処理落ちがない場合）。異なる並びは 16×4×45 = 2880 通り。
  H = 最初のキューブの高さの番号(0〜15)  S = c0 の bit2-3（隣り合う高さの入れ替わり方 A〜D）
  T = 同じ H・S の中での残りの違い 45 通り（代表の c0 が小さい順）
"""
# 1個目からの出現タイミング（フレーム数。MAME で通しで記録した値。全て16の倍数）
DELTAS = [0, 32, 112, 192, 240, 304, 320, 352, 384, 448, 480, 528, 560, 592, 640, 688, 704, 736, 768, 784, 816, 848, 896, 944, 1024, 1056, 1136, 1216, 1264, 1328, 1344, 1376, 1408, 1472, 1504, 1552, 1584, 1616, 1664, 1712, 1728, 1760, 1792, 1808, 1840, 1872, 1920, 1968, 2048, 2080, 2160, 2240, 2288, 2352, 2368, 2400, 2432, 2496, 2528, 2576, 2608, 2640, 2688, 2736, 2752, 2784, 2816, 2832, 2864, 2896, 2944, 2992, 3072, 3104, 3184, 3264, 3312, 3376, 3392, 3424, 3456, 3520, 3552, 3600, 3632, 3664, 3712, 3760, 3776, 3808, 3840, 3856, 3888, 3920, 3968, 4016, 4096, 4128, 4208]
NH, NS, NT = 16, 4, 45

def slot(v):
    return (((v & 0xff) ^ (v >> 8)) & 0x3c) >> 2

def table():
    """[h][s][t] -> c0 の平たい表 (h*4+s)*45+t"""
    groups = {}
    for c0 in range(0, 65536, 4):
        seq = tuple(slot((c0 + d) & 0xffff) for d in DELTAS)
        key = (seq[0], (c0 >> 2) & 3)
        g = groups.setdefault(key, {})
        if seq not in g: g[seq] = c0
    out = []
    for h in range(NH):
        for s in range(NS):
            g = groups[(h, s)]
            assert len(g) == NT, (h, s, len(g))
            out += sorted(g.values())
    return out

if __name__ == '__main__':
    t = table(); print(len(t), [hex(x) for x in t[:8]])
